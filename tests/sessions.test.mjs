import assert from "node:assert/strict";
import { isActive, statusLabel, durationLabel, sessionCandidates, sessionOutput, SessionRotation } from "../ui/session-format.js";

assert.equal(isActive({status:"running"}), true);
assert.equal(isActive({status:"active"}), true);
assert.equal(isActive({status:"unknown"}), false);
assert.equal(isActive({status:"completed"}), false);
assert.equal(statusLabel("active"), "近期活动");
assert.equal(statusLabel("unexpected"), "状态未知");
const now = 1_800_000_000_000;
assert.equal(durationLabel(now - 88_000, now), "01:28");
assert.equal(durationLabel(now - 3_661_000, now), "1:01:01");
assert.equal(durationLabel(now + 1000, now), "00:00");
assert.equal(durationLabel(null, now), "");
const active = {id:"one",appType:"codex",status:"running",lastActiveAt:now,startedAt:now,entries:[{kind:"assistant",text:"上一轮",timestamp:now-1000},{kind:"assistant",text:"你好",timestamp:now}]};
const second = {...active,id:"two"};
const complete = {...active,id:"done",status:"completed",lastActiveAt:now-5000};
assert.deepEqual(sessionCandidates([complete,active], "codex", 15, now), [active]);
assert.deepEqual(sessionCandidates([complete], "codex", 15, now), [complete]);
assert.deepEqual(sessionCandidates([complete], "codex", 15, now+10_000), []);
assert.deepEqual(sessionCandidates([active], "claude", 15, now), []);
assert.equal(sessionOutput(active), "你好");
assert.equal(sessionOutput({...active,startedAt:now+1}), "等待输出…");
assert.equal(sessionOutput({...active,entries:[{kind:"tool",title:"Bash",text:"ok",timestamp:now}]}), "Bash · ok");
const rotation = new SessionRotation();
assert.equal(rotation.current("codex", [active,second]).id, "one");
assert.equal(rotation.current("codex", [second,active]).id, "one");
assert.equal(rotation.next("codex", [active,second]).id, "two");
assert.equal(rotation.next("codex", [active,second],-1).id, "one");
assert.equal(rotation.current("codex", [second]).id, "two");
assert.equal(rotation.next("codex", []), null);
console.log("会话筛选、轮播、计时与本轮输出测试通过");
